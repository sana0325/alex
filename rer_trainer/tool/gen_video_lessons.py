def title(t, sub, say):
    return {'type': 'title', 'title': t, 'subtitle': sub, 'say': say}


def bullets(t, items, say):
    return {'type': 'bullets', 'title': t, 'items': items, 'say': say}


def kind(k, caption, say):
    return {'type': 'kind', 'kind': k, 'caption': caption, 'say': say}


def preset(i, caption, say):
    return {'type': 'preset', 'index': i, 'caption': caption, 'say': say}


def uav(pid, view, caption, say):
    return {'type': 'uav', 'profile': pid, 'view': view, 'caption': caption, 'say': say}


def iq(slots, caption, say):
    return {'type': 'iq', 'slots': slots, 'caption': caption, 'say': say}


