def f(t, s):
    return {'t': t, 's': s}


def sig(prim, off, dbm, **p):
    # Широкосмугове відео розподіляє потужність на багато бінів — у синтетиці
    # піднімаємо рівень, щоб воно було помітне над шумом, як на реальному РЕР.
    if prim == 'ofdm_block' and dbm < -90:
        dbm += 14
    d = {'prim': prim, 'off_mhz': off, 'dbm': dbm}
    if p:
        d['p'] = p
    return d


def view(title, role, center, span, signals, **kw):
    v = {'title': title, 'role': role, 'center_mhz': center, 'span_mhz': span, 'signals': signals}
    v.update(kw)
    return v


def row(channel, rng, typ, shape, width, s):
    return {'channel': channel, 'range': rng, 'type': typ, 'shape': shape, 'width': width, 's': s}


